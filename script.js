/* Tab Switching */
function switchTab(tabId) {
  document.querySelectorAll('.nav-btn').forEach(btn => btn.classList.remove('active'));
  document.querySelectorAll('.tab-section').forEach(sec => sec.classList.remove('active'));

  document.getElementById(`tab-${tabId}`).classList.add('active');
  document.getElementById(`sec-${tabId}`).classList.add('active');
}

/* Bhashini Dynamic Translation Handler */
function changeLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(elem => {
    const key = elem.getAttribute('data-i18n');
    if (t[key]) {
      elem.textContent = t[key];
    }
  });

  if (currentFarmerData) {
    updatePassUIDisplay();
  }

  addLog(`Bhashini Language changed to: ${lang === 'hi' ? 'Hindi (हिन्दी)' : 'English'}`);
}

/* Step 1: OTP Auth with 20s Countdown */
function handleOtpClick() {
  const mobile = document.getElementById('mobileInput').value;

  if (!isOtpSent) {
    if (!mobile || mobile.length < 10) {
      alert(currentLang === 'hi' ? "कृपया 10-अंकीय वैध मोबाइल नंबर दर्ज करें।" : "Please enter a valid 10-digit mobile number.");
      return;
    }

    generatedOtp = Math.floor(100000 + Math.random() * 900000).toString();
    isOtpSent = true;

    document.getElementById('otpInputGroup').classList.remove('hidden');
    document.getElementById('otpBtnText').textContent = translations[currentLang].verifyOtp;

    alert(`${currentLang === 'hi' ? 'आपका डेमो ओटीपी है' : 'Your Demo OTP is'}: ${generatedOtp}`);

    const smsMsg = currentLang === 'hi' 
      ? `आपका एपीएमसी ओटीपी ${generatedOtp} है। यह 20 सेकंड के लिए मान्य है।`
      : `Your APMC Demo OTP is ${generatedOtp}. Valid for 20 seconds.`;
    document.getElementById('farmerSmsInbox').textContent = smsMsg;

    addLog(`Demo OTP sent. +91-${mobile} [OTP: ${generatedOtp}]`);

    timerSeconds = 20;
    document.getElementById('timerVal').textContent = timerSeconds;

    clearInterval(otpTimer);
    otpTimer = setInterval(() => {
      timerSeconds--;
      document.getElementById('timerVal').textContent = timerSeconds;

      if (timerSeconds <= 0) {
        clearInterval(otpTimer);
        alert(currentLang === 'hi' ? "ओटीपी समाप्त हो गया है! कृपया पुन: प्रयास करें।" : "OTP Expired! Please try again.");
        resetOtpState();
      }
    }, 1000);

  } else {
    const enteredOtp = document.getElementById('otpCodeInput').value;
    if (enteredOtp === generatedOtp) {
      clearInterval(otpTimer);
      alert(currentLang === 'hi' ? "सत्यापन सफल! कृपया फसल और स्लॉट विवरण भरें।" : "Authentication successful! Please fill produce details.");

      document.getElementById('otpCard').classList.add('hidden');
      document.getElementById('bookingFormCard').classList.remove('hidden');

      addLog("Farmer authenticated successfully.");
    } else {
      alert(currentLang === 'hi' ? "गलत ओटीपी! कृपया पुन: प्रयास करें।" : "Invalid OTP! Please check and try again.");
    }
  }
}

function resetOtpState() {
  isOtpSent = false;
  document.getElementById('otpInputGroup').classList.add('hidden');
  document.getElementById('otpBtnText').textContent = translations[currentLang].sendOtp;
  document.getElementById('otpCodeInput').value = '';
}

/* Step 2 & 3: Custom Pass Generation & Hard Stop Quota Limit */
function generateDigitalPass() {
  const name = document.getElementById('farmerNameInput').value.trim() || "Ramesh Patil";
  const mandi = document.getElementById('mandiSelect').value;
  const commodity = document.getElementById('commoditySelect').value;
  const quantity = parseFloat(document.getElementById('quantityInput').value) || 5;
  const vehicle = document.getElementById('vehicleSelect').value;
  const baseSlot = document.getElementById('timeSlotSelect').value;

  // HARD STOP: Quota Limit Check
  if (currentBookedQuota + quantity > MAX_DAILY_QUOTA) {
    const alertMsg = currentLang === 'hi'
      ? `दैनिक कोटा पूर्ण हो गया है! केवल ${MAX_DAILY_QUOTA - currentBookedQuota} टन उपलब्ध है।`
      : `Daily Quota Exceeded! Only ${MAX_DAILY_QUOTA - currentBookedQuota} Tons remaining. Booking stopped.`;
    alert(alertMsg);
    return;
  }

  // Update Quota Tracker
  currentBookedQuota += quantity;
  const quotaPercent = Math.min(100, Math.round((currentBookedQuota / MAX_DAILY_QUOTA) * 100));
  document.getElementById('quotaProgressBar').style.width = `${quotaPercent}%`;
  document.getElementById('quotaText').textContent = `${currentBookedQuota} / ${MAX_DAILY_QUOTA} Tons Booked`;

  const randomToken = "MND-" + Math.floor(10000 + Math.random() * 90000);

  currentFarmerData = {
    token: randomToken,
    name: name,
    mandi: mandi,
    commodity: commodity,
    quantity: quantity,
    vehicle: vehicle,
    eta: baseSlot,
    position: "#3"
  };

  updatePassUIDisplay();

  // Generate QR Code
  document.getElementById('qrImage').src = `https://api.qrserver.com/v1/create-qr-code/?size=180x180&data=${randomToken}`;

  // Hide form, reveal pass card
  document.getElementById('bookingFormCard').classList.add('hidden');
  document.getElementById('digitalPassCard').classList.remove('hidden');

  // Update Officer Desk default token
  document.getElementById('officerTokenInput').value = randomToken;
  document.getElementById('procToken').textContent = `#${randomToken}`;
  document.getElementById('procFarmer').textContent = name;
  document.getElementById('procCommodity').textContent = commodity;

  addLog(`Pass Created: ${randomToken} - ${name} [${quantity} Tons ${commodity}]`);
}

function updatePassUIDisplay() {
  if (!currentFarmerData) return;

  document.getElementById('passTokenDisplay').textContent = `#${currentFarmerData.token}`;
  document.getElementById('dispFarmerName').textContent = currentFarmerData.name;
  document.getElementById('dispMandiCenter').textContent = currentFarmerData.mandi;
  document.getElementById('dispCommodity').textContent = currentFarmerData.commodity;
  document.getElementById('dispQuantity').textContent = `${currentFarmerData.quantity} Tons`;
  document.getElementById('dispVehicle').textContent = currentFarmerData.vehicle;
  document.getElementById('dispEta').textContent = currentFarmerData.eta;
  document.getElementById('dispPosition').textContent = currentFarmerData.position;
}

/* Machine Slowdown Simulation & SMS Notice */
function simulateMachineSlowdown() {
  document.getElementById('efficiencySelect').value = "25"; // Slow speed
  recalculateThroughput();

  if (currentFarmerData) {
    const newTime = "11:30 AM (Delayed)";
    currentFarmerData.eta = newTime;
    document.getElementById('dispEta').textContent = newTime;

    // Show Portal Delay Banner
    const delayNotice = document.getElementById('portalDelayAlert');
    delayNotice.classList.remove('hidden');

    const smsText = currentLang === 'hi'
      ? `सूचना: धर्म कांटा मंदी के कारण आपका आगमन समय बदलकर ${newTime} कर दिया गया है। टोकन: #${currentFarmerData.token}`
      : `ALERT: Machine slowdown at Mandi weighbridge. Your arrival time changed to ${newTime}. Token: #${currentFarmerData.token}`;

    document.getElementById('farmerSmsInbox').textContent = smsText;
    addLog(`Broadcast SMS: ${smsText}`);

    alert(currentLang === 'hi' 
      ? "मशीन की मंदी दर्ज की गई! किसान के पोर्टल पर समय अपडेट कर एसएमएस भेजा गया।" 
      : "Machine slowdown triggered! Time updated on portal & SMS sent to farmer.");
  } else {
    alert("Machine slowdown applied to system queue.");
  }
}

/* Bhashini Text-To-Speech Audio Narration */
function speakPassStatus() {
  if ('speechSynthesis' in window) {
    window.speechSynthesis.cancel();

    if (!currentFarmerData) return;

    let textToSpeak = "";
    if (currentLang === 'hi') {
      textToSpeak = `नमस्ते ${currentFarmerData.name}। आपका डिजिटल पास ${currentFarmerData.token} ${currentFarmerData.mandi} के लिए पुष्ट किया गया है। आपकी उपज ${currentFarmerData.quantity} टन ${currentFarmerData.commodity} है। आपकी कतार स्थिति ${currentFarmerData.position} है और आगमन का समय ${currentFarmerData.eta} है।`;
    } else {
      textToSpeak = `Hello ${currentFarmerData.name}. Your digital pass ${currentFarmerData.token} is confirmed for ${currentFarmerData.mandi}. Produce: ${currentFarmerData.quantity} tons of ${currentFarmerData.commodity}. Live position: ${currentFarmerData.position}, arrival time: ${currentFarmerData.eta}.`;
    }

    const utterance = new SpeechSynthesisUtterance(textToSpeak);
    utterance.lang = currentLang === 'hi' ? 'hi-IN' : 'en-US';
    utterance.rate = 0.9;

    window.speechSynthesis.speak(utterance);
    addLog(`Bhashini TTS Narration triggered [${currentLang.toUpperCase()}]`);
  } else {
    alert("Text-to-speech is not supported in your browser.");
  }
}

